def current_language() -> str:
    """Return the active presentation language without mutating engine state."""
    language = st.session_state.get(LANGUAGE_KEY, "en")
    return language if language in SUPPORTED_LANGUAGES else "en"


def direction() -> str:
    return "rtl" if current_language() == "ar" else "ltr"


def is_arabic() -> bool:
    return current_language() == "ar"


def t(message_key: str, **parameters) -> str:
    """Translate a registered interface message and interpolate named values."""
    template = MESSAGES[current_language()][message_key]
    return template.format(**parameters) if parameters else template


def term(display_value: object) -> str:
    """Translate a canonical option label while preserving its stored value."""
    text = str(display_value)
    return _ARABIC_TERMS.get(text, text) if is_arabic() else text


def validation_message(message: object) -> str:
    """Translate a validation problem without changing its canonical source."""
    text = str(message)
    if not is_arabic():
        return text
    fixed_translation = _ARABIC_VALIDATION_MESSAGES.get(text)
    if fixed_translation:
        return fixed_translation

    match = re.fullmatch(r"Unknown isotope '([^']+)'\.", text)
    if match:
        return f"النظير المشع «{match.group(1)}» غير معروف."
    match = re.fullmatch(r"Duplicate wall '([^']+)'\.", text)
    if match:
        return f"الحائط «{match.group(1)}» مكرر."
    match = re.fullmatch(r"Wall ([^:]+): negative thickness\.", text)
    if match:
        return f"الحائط {match.group(1)}: سُمك سالب."
    match = re.fullmatch(r"Wall ([^:]+): occupancy factor must be > 0\.", text)
    if match:
        return f"الحائط {match.group(1)}: يجب أن يكون معامل الإشغال أكبر من صفر."
    match = re.fullmatch(
        r"Wall ([^:]+): opening '([^']+)' does not fit on the wall\.", text
    )
    if match:
        opening_kind = _ARABIC_TERMS.get(match.group(2).title(), match.group(2))
        return f"الحائط {match.group(1)}: فتحة {opening_kind} لا تتسع داخل الحائط."

    wall_patterns = (
        (r"uses an unsupported primary material\.", "يستخدم مادة أولية غير مدعومة."),
        (r"uses an unsupported second material\.", "يستخدم مادة ثانية غير مدعومة."),
        (r"primary thickness must be between 0 and 3,000 mm\.", "يجب أن يكون السُمك الأولي بين 0 و3,000 مم."),
        (r"second thickness must be between 0 and 3,000 mm\.", "يجب أن يكون سُمك الطبقة الثانية بين 0 و3,000 مم."),
        (r"has an unsupported area classification\.", "يحتوي على تصنيف منطقة غير مدعوم."),
        (r"occupancy factor must be between 0\.0001 and 1\.", "يجب أن يكون معامل الإشغال بين 0.0001 و1."),
        (r"custom design goal is outside the editor range\.", "هدف التصميم المخصص خارج نطاق المحرر."),
    )
    for suffix_pattern, translation in wall_patterns:
        match = re.fullmatch(rf"Wall ([^ ]+) {suffix_pattern}", text)
        if match:
            return f"الحائط {match.group(1)} {translation}"

    opening_patterns = (
        (r"has an unsupported opening type\.", "نوع الفتحة غير مدعوم."),
        (r"width must be between 0\.1 and 40 m\.", "يجب أن يكون العرض بين 0.1 و40 م."),
        (r"lead equivalence must be between 0 and 100 mm\.", "يجب أن يكون مكافئ الرصاص بين 0 و100 مم."),
        (r"radius must be between 1 and 300 mm\.", "يجب أن يكون نصف القطر بين 1 و300 مم."),
        (r"return-wall material is unsupported\.", "مادة الحائط الراجع غير مدعومة."),
    )
    for suffix_pattern, translation in opening_patterns:
        match = re.fullmatch(
            rf"Wall ([^ ]+) (door|window|duct|maze) {suffix_pattern}", text
        )
        if match:
            opening_kind = _ARABIC_TERMS.get(match.group(2).title(), match.group(2))
            return f"الحائط {match.group(1)}، فتحة {opening_kind}: {translation}"

    match = re.fullmatch(
        r"Wall ([^ ]+) (door|window|duct|maze) (.+) is outside the editor range\.",
        text,
    )
    if match:
        opening_kind = _ARABIC_TERMS.get(match.group(2).title(), match.group(2))
        field_labels = {
            "corridor length": "طول الممر",
            "shadow offset": "إزاحة الظل",
            "return thickness": "سُمك الحائط الراجع",
        }
        field_label = field_labels.get(match.group(3), match.group(3))
        return (
            f"الحائط {match.group(1)}، فتحة {opening_kind}: "
            f"{field_label} خارج نطاق المحرر."
        )
    return term(text)


def html_attributes() -> str:
    return f'lang="{current_language()}" dir="{direction()}"'


def locale_marker_html() -> str:
    return (
        f'<div class="sl-locale-marker" {html_attributes()} '
        f'data-language="{escape(current_language())}" aria-hidden="true"></div>'
    )


def _store_selected_language() -> None:
    """Copy the page-scoped widget choice into durable navigation state."""
    selected = st.session_state.get(LANGUAGE_CONTROL_KEY)
    if selected in SUPPORTED_LANGUAGES:
        st.session_state[LANGUAGE_KEY] = selected


def render_language_switcher(*, compact: bool = False) -> None:
    """Render the shared language control, with an optional compact top-rail form."""
    active_language = current_language()
    st.session_state[LANGUAGE_KEY] = active_language
    st.session_state[LANGUAGE_CONTROL_KEY] = active_language
    compact_labels = {"en": "EN", "ar": "ع"}
    st.segmented_control(
        t("language"),
        SUPPORTED_LANGUAGES,
        format_func=lambda language: (
            compact_labels[language] if compact else LANGUAGE_NAMES[language]
        ),
        key=LANGUAGE_CONTROL_KEY,
        on_change=_store_selected_language,
        selection_mode="single",
        required=True,
        width="content" if compact else "stretch",
        label_visibility="collapsed",
    )




